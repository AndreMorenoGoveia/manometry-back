"""One textbook swallow topography per diagnosis, for the reference gallery.

The images are real examinations from the held-out partition, so they are not
committed here: `assets/reference/` is generated by
`scripts/export_reference_images.py` and ignored by git.  What *is* committed is
`assets/reference_manifest.json`, which records only which anonymous exam and
which swallow was chosen, which is enough to regenerate the gallery and holds
no pixels.

If neither the exported PNG nor the dataset is present the route answers 404 and
the interface falls back to its own rendering, so a checkout without the data
still runs.
"""
from __future__ import annotations

import json
import threading
from pathlib import Path

from .config import SETTINGS

MANIFEST_PATH = Path(__file__).resolve().parent.parent / "assets" / "reference_manifest.json"

_CACHE: dict[str, bytes | None] = {}
_LOCK = threading.Lock()


def load_manifest() -> dict[str, dict]:
    if not MANIFEST_PATH.is_file():
        return {}
    try:
        payload = json.loads(MANIFEST_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return payload.get("references", {})


def _resolve(slug: str) -> bytes | None:
    exported = SETTINGS.reference_dir / f"{slug}.png"
    if exported.is_file():
        return exported.read_bytes()

    entry = load_manifest().get(slug)
    if not entry:
        return None
    candidate = (
        SETTINGS.dataset_root
        / entry.get("split", "test")
        / slug
        / entry.get("exam", "")
        / entry.get("swallow", "")
    )
    # Guard against a manifest entry escaping the dataset root.
    try:
        candidate = candidate.resolve()
        candidate.relative_to(SETTINGS.dataset_root.resolve())
    except (OSError, ValueError):
        return None
    return candidate.read_bytes() if candidate.is_file() else None


def reference_png(slug: str) -> bytes | None:
    """PNG bytes of the reference topography for ``slug``, or None."""
    if slug in _CACHE:
        return _CACHE[slug]
    with _LOCK:
        if slug not in _CACHE:
            _CACHE[slug] = _resolve(slug)
    return _CACHE[slug]


def clear_cache() -> None:
    with _LOCK:
        _CACHE.clear()
